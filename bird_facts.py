def get_bird_facts(label: str) -> dict | None:
    """Return facts for a classifier label, ignoring capitalization."""
    return BIRD_FACTS.get(label.casefold())


def slugify_bird_label(label: str) -> str:
    """Convert a classifier label into its detail-page URL slug."""
    return "-".join(label.casefold().split())
